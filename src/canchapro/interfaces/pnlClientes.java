    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
         String codigo = txtCodigoCliente.getText().trim();
    String nombre = txtNombreCliente.getText().trim();
    String telefono = txtTelefonoCliente.getText().trim();
    String correo = txtCorreoCliente.getText().trim();

    if (codigo.isEmpty() || nombre.isEmpty() || telefono.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Complete código, nombre y teléfono");
        } else if (codigo.contains(",") || nombre.contains(",") || telefono.contains(",") || correo.contains(",")) {
    JOptionPane.showMessageDialog(this, "No use comas en los campos");

    } else {
        Cliente nuevo = new Cliente(codigo, nombre, telefono, LocalDate.now());
        if (!correo.isEmpty()) {
            nuevo.setCorreo(correo);
        }
        String mensaje = gestionClientes.agregarCliente(nuevo);
        JOptionPane.showMessageDialog(this, mensaje);
        if (mensaje.equals("Cliente agregado correctamente")) {
            limpiarCampos();
            refrescarTabla();
        }
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String codigo = txtCodigoCliente.getText().trim();
    String telefono = txtTelefonoCliente.getText().trim();
    String nombre = txtNombreCliente.getText().trim();

    DefaultTableModel modelo = (DefaultTableModel) tblClientes.getModel();
    modelo.setRowCount(0);
    int encontrados = 0;

    if (!codigo.isEmpty()) {
        Cliente c = gestionClientes.buscarClienteporCodigo(codigo);
        if (c != null) {
            agregarFila(modelo, c);
            encontrados = 1;
        }
    } else if (!telefono.isEmpty()) {
        Cliente c = gestionClientes.buscarClienteporTelefono(telefono);
        if (c != null) {
            agregarFila(modelo, c);
            encontrados = 1;
        }
    } else if (!nombre.isEmpty()) {
        Cliente[] lista = gestionClientes.buscarClientesPorNombre(nombre);
        for (int i = 0; i < lista.length; i++) {
            agregarFila(modelo, lista[i]);
        }
        encontrados = lista.length;
    } else {
        JOptionPane.showMessageDialog(this, "Escriba un código, teléfono o nombre para buscar");
        refrescarTabla();
        return;
    }

    if (encontrados == 0) {
        JOptionPane.showMessageDialog(this, "No se encontró ningún cliente");
        refrescarTabla();
    }

    }//GEN-LAST:event_btnBuscarActionPerformed


