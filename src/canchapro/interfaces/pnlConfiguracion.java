    private void btnGuardarCambiosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarCambiosActionPerformed
        try {
        double dia = Double.parseDouble(txtTarifaDia.getText().trim().replace(",", "."));
        double noche = Double.parseDouble(txtTarifaNoche.getText().trim().replace(",", "."));
        double finSemana = Double.parseDouble(txtTarifaFinDeSemana.getText().trim().replace(",", "."));
        double porcentaje = Double.parseDouble(txtAnticipo.getText().trim().replace(",", "."));

        if (dia <= 0 || noche <= 0 || finSemana <= 0) {
            JOptionPane.showMessageDialog(this, "Las tarifas deben ser mayores a 0");
        } else if (porcentaje < 0 || porcentaje > 100) {
            JOptionPane.showMessageDialog(this, "El anticipo debe estar entre 0 y 100");
        } else {
            tarifa.setLunesViernesMatutino(dia);
            tarifa.setLunesViernesVespertino(noche);
            tarifa.setFinesDeSemana(finSemana);
            tarifa.setPorcentajeAnticipoMinimo(porcentaje / 100);
            JOptionPane.showMessageDialog(this, "Configuración actualizada. Presione Guardar en Archivos para conservarla");
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Escriba solo números");
    }

    }//GEN-LAST:event_btnGuardarCambiosActionPerformed


